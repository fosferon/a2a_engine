defmodule A2aEngine.Types.Artifact do
  @moduledoc """
  A file, data, or text resource generated by an agent during a task.

  Required: `artifactId`, `parts`. No `kind` discriminator (spec choice).
  """

  alias A2aEngine.Types.Part

  @type t :: %__MODULE__{
          artifact_id: String.t(),
          parts: [Part.t()],
          name: String.t() | nil,
          description: String.t() | nil,
          extensions: [String.t()] | nil,
          metadata: map() | nil
        }

  @enforce_keys [:artifact_id, :parts]
  defstruct [:artifact_id, :parts, :name, :description, :extensions, :metadata]

  @spec to_map(t()) :: map()
  def to_map(%__MODULE__{} = a) do
    %{
      "artifactId" => a.artifact_id,
      "parts" => Enum.map(a.parts, &Part.encode/1)
    }
    |> maybe_put("name", a.name)
    |> maybe_put("description", a.description)
    |> maybe_put("extensions", a.extensions)
    |> maybe_put("metadata", a.metadata)
  end

  @spec from_map(map()) :: {:ok, t()} | {:error, term()}
  def from_map(%{"artifactId" => aid, "parts" => parts_list} = m)
      when is_binary(aid) and is_list(parts_list) do
    with {:ok, parts} <- Part.decode_list(parts_list) do
      {:ok,
       %__MODULE__{
         artifact_id: aid,
         parts: parts,
         name: m["name"],
         description: m["description"],
         extensions: m["extensions"],
         metadata: m["metadata"]
       }}
    end
  end

  def from_map(_), do: {:error, :invalid_artifact}

  defp maybe_put(m, _k, nil), do: m
  defp maybe_put(m, k, v), do: Map.put(m, k, v)
end
